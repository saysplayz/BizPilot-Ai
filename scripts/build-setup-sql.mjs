#!/usr/bin/env node
// BizPilot AI · Part 1 — Database & Security
// Owner: Member 1 (see TEAM.md)
// Builds supabase/setup.sql: every migration in supabase/migrations (in filename
// order) in one file, for pasting into the Supabase SQL Editor on a fresh project.
// Usage: node scripts/build-setup-sql.mjs   (run again whenever a migration changes)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "supabase", "migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();

const header = `-- =============================================================================
-- BizPilot AI — ONE-SHOT DATABASE SETUP for a hosted Supabase project.
--
-- How to use: Supabase → SQL Editor → + New query → paste this WHOLE file → Run.
-- If Supabase warns about "destructive operations" / "RLS", choose
-- "Run without RLS": migration 0008 enables Row Level Security on every table.
-- Run it ONCE on a fresh project. It contains every file in supabase/migrations
-- (in order), then backfills profiles for accounts created before setup and
-- tells the Supabase API to reload its schema.
--
-- GENERATED by scripts/build-setup-sql.mjs — edit the migrations, not this file.
-- =============================================================================
`;

const body = files.map((f) => `\n-- >>>>> ${f} >>>>>\n\n${readFileSync(join(dir, f), "utf8").trimEnd()}\n`).join("");

const footer = `
-- >>>>> post-setup >>>>>

-- Accounts that signed up before the tables existed have no profile row yet.
insert into public.profiles (id, full_name)
select u.id, left(u.raw_user_meta_data ->> 'full_name', 120)
from auth.users u
on conflict (id) do nothing;

-- Make the new tables and functions visible to the app immediately.
notify pgrst, 'reload schema';
`;

writeFileSync(join(root, "supabase", "setup.sql"), header + body + footer);
console.log(`supabase/setup.sql written from ${files.length} migrations`);
